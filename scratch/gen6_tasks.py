    if not ok:
        return ok, detail

    # ── Artifact / completeness checks ──
    import glob as _glob
    # BSA
    if not _glob.glob(os.path.join(d, "specs", "*.md")):
        return False, "NO SPECS: specs/SPEC-*.md missing"
    # App entry
    if not any(os.path.isfile(os.path.join(d, e)) for e in ("server.js", "app.js", "index.js")):
        return False, "NO APP ENTRY"
    # SDET: tests exist and pass
    tests = _glob.glob(os.path.join(d, "tests", "*.test.js"))
    if not tests:
        return False, "NO TESTS: tests/ suite missing"
    try:
        r = subprocess.run(["node", "--test"], cwd=d, capture_output=True, text=True, timeout=180)
        if r.returncode != 0:
            tail = (r.stdout or "")[-400:] + (r.stderr or "")[-400:]
            return False, "TESTS FAIL rc=" + str(r.returncode) + " " + tail
    except Exception as e:
        return False, "TESTS ERROR: " + str(e)
    # DevSecOps
    src_all = ""
    for root, _dirs, files in os.walk(d):
        if "node_modules" in root:
            continue
        for fn in files:
            if fn.endswith(".js"):
                try:
                    src_all += open(os.path.join(root, fn), encoding="utf-8", errors="replace").read()
                except Exception:
                    pass
    if "bcrypt" not in src_all:
        return False, "SECURITY: bcrypt missing"
    if "helmet" not in src_all:
        return False, "SECURITY: helmet missing"
    # Completeness: 25+ real source files (exclude node_modules, specs, tests, lockfiles)
    real = 0
    for root, dirs, files in os.walk(d):
        dirs[:] = [x for x in dirs if x != "node_modules"]
        if "node_modules" in root:
            continue
        for fn in files:
            if fn.endswith((".js", ".html", ".css", ".md")) and fn not in ("package-lock.json", "bsa_telemetry.jsonl"):
                real += 1
    frontend = _glob.glob(os.path.join(d, "public", "*.html")) + _glob.glob(os.path.join(d, "public", "js", "*.js"))
    if real < 25:
        return False, f"TOO FEW REAL FILES ({real} < 25) — build is incomplete (AI slop)"
    if len(frontend) < 8:
        return False, f"FRONTEND INCOMPLETE ({len(frontend)} pages/modules) — real storefront required"

    return True, "ecom ok (api + frontend + specs + tests + security + completeness)"
